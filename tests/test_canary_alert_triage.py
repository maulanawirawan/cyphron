"""test_canary_alert_triage — triase alert canarytoken, nol jaringan."""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1] / "tools"
sys.path.insert(0, str(TOOLS))

import canary_alert_triage as cat  # noqa: E402


def _run(*paths: Path) -> tuple[int, dict | None]:
    args = []
    for p in paths:
        args += ["--alert", str(p)]
    proc = subprocess.run(
        [sys.executable, str(TOOLS / "canary_alert_triage.py"), *args],
        capture_output=True, text=True)
    out = json.loads(proc.stdout) if proc.stdout.strip() else None
    return proc.returncode, out


def _tmp(tmp_path: Path, name: str, data) -> Path:
    p = tmp_path / name
    if isinstance(data, bytes):
        p.write_bytes(data)
    else:
        p.write_text(data, encoding="utf-8")
    return p


EML = """From: alerts@canarytokens.org
To: soc@corp.example
Subject: Canarytoken triggered (HTTP token)
Content-Type: text/plain; charset=utf-8

A canary token was triggered!
Token type: http-canary
Memo: DNS recon on corp.example
Source IP: 203.0.113.44
User-Agent: Mozilla/5.0 (Windows NT 10.0) curl/8.1
URL: https://canarytokens.org/history?token=abc123

This alert was generated by canarytokens.org.
"""


def test_eml_alert(tmp_path):
    p = _tmp(tmp_path, "alert.eml", EML)
    code, out = _run(p)
    assert code == 0 and out["alerts"] == 1
    tr = [f for f in out["findings"] if f["type"] == "canary-triggered"]
    assert tr and tr[0]["severity"] == "high"
    assert tr[0]["evidence"]["src_ip"] == "203.0.113.44"
    assert "DNS recon" in tr[0]["evidence"]["memo"]
    info = [f for f in out["findings"] if f["type"] == "source-info"]
    assert info


def test_json_webhook(tmp_path):
    data = {
        "token_type": "dns",
        "memo": "canary in prod DNS zone",
        "src_ip": "198.51.100.7",
        "user_agent": "dig/9.18",
        "url": "https://canarytokens.org/history?token=zzz",
    }
    p = _tmp(tmp_path, "webhook.json", json.dumps(data))
    code, out = _run(p)
    assert code == 0
    tr = [f for f in out["findings"] if f["type"] == "canary-triggered"]
    assert tr and tr[0]["evidence"]["token_type"] == "dns"


def test_multiple_alerts_and_unparseable(tmp_path):
    p1 = _tmp(tmp_path, "a.eml", EML)
    p2 = _tmp(tmp_path, "b.json", json.dumps({
        "token_type": "pdf", "memo": "payroll bait", "src_ip": "198.51.100.8"}))
    p3 = _tmp(tmp_path, "junk.txt", "totally unrelated file")
    code, out = _run(p1, p2, p3)
    assert code == 0 and out["alerts"] == 2
    unp = [f for f in out["findings"] if f["type"] == "unparseable"]
    assert unp and any("junk.txt" in x for x in unp[0]["evidence"]["files"])


def test_fail_closed(tmp_path):
    p = _tmp(tmp_path, "junk.eml", "hello world, no canary here")
    code, out = _run(p)
    assert code == 2 and out is None
    code2, _ = _run(tmp_path / "missing.eml")
    assert code2 == 2


def test_eml_parser_unit():
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        p = Path(td) / "a.eml"
        p.write_bytes(EML.encode())
        a = cat._parse_eml(p)
        assert a is not None
        assert a["src_ip"] == "203.0.113.44"
        assert a["token_type"] == "http-canary"
