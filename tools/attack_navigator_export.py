"""[SAFETY: read-only, NOL jaringan] attack_navigator_export — ekspor layer
MITRE ATT&CK Navigator (JSON) dari laporan attack_coverage atau daftar teknik.
Blue-bridge: visualisasi cakupan. TIDAK ada jaringan.

Dibangun FROM SCRATCH, stdlib murni.

Ceruk vs modul lain (anti-duplikasi):
  - `attack_coverage.py` = MENGHITUNG matriks cakupan. Tool ini meng-EKSPOR
    layer Navigator yang bisa diunggah ke ATT&CK Navigator, plus findings.json
    paralel (L0 count).

Verdict: ekspor = L0 OBSERVED (ringkasan hitung). Selalu >=1 finding.

Input -> mekanisme -> output:
  - Input : --coverage <JSON attack_coverage {techniques:[{id,state|score}]}> ATAU
            --techniques "T1059:100,T1071:50,T1566" (id[:score], pisah koma);
            --name <nama layer>; --out-layer <tulis layer JSON>.
  - Output: JSON kontrak; --out; --fail-on. Exit 0/2.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "core"))
from findings import make_finding, write_findings  # noqa: E402

SCHEMA = "cyphron.attack-navigator-export/1"
TOOL = "attack-navigator-export"
_TID = re.compile(r"^T\d{4}(?:\.\d{3})?$")
STATE_SCORE = {"covered": 100, "partial": 50, "gap": 0, "detected": 100,
               "mitigated": 100, "none": 0}


def _color(score: int) -> str:
    if score >= 70:
        return "#2ca25f"      # hijau: tercakup
    if score >= 1:
        return "#fec44f"      # kuning: parsial
    return "#de2d26"          # merah: gap


def _tech_entry(tid: str, score: int, comment: str = "") -> dict:
    return {"techniqueID": tid, "score": int(score), "color": _color(int(score)),
            "comment": comment, "enabled": True}


def _parse_techniques(spec: str) -> list[dict]:
    out = []
    for item in spec.split(","):
        item = item.strip()
        if not item:
            continue
        tid, _, sc = item.partition(":")
        tid = tid.strip().upper()
        if not _TID.match(tid):
            raise ValueError("technique id tak valid: %r (format T1059 / T1059.001)" % tid)
        score = int(sc) if sc.strip().isdigit() else 100
        out.append(_tech_entry(tid, score))
    if not out:
        raise ValueError("nol teknik")
    return out


def _from_coverage(doc: dict) -> list[dict]:
    techs = doc.get("techniques") if isinstance(doc, dict) else None
    if not isinstance(techs, list):
        raise ValueError("coverage harus {techniques:[...]}")
    out = []
    for t in techs:
        if not isinstance(t, dict):
            continue
        tid = str(t.get("id") or t.get("techniqueID") or "").upper()
        if not _TID.match(tid):
            continue
        if "score" in t and isinstance(t["score"], (int, float)):
            score = int(t["score"])
        else:
            score = STATE_SCORE.get(str(t.get("state", "")).lower(), 0)
        out.append(_tech_entry(tid, score, str(t.get("comment", ""))))
    if not out:
        raise ValueError("coverage tak memuat teknik valid")
    return out


def build_layer(techniques: list[dict], name: str) -> dict:
    return {
        "name": name, "versions": {"layer": "4.5", "navigator": "4.9.5",
                                   "attack": "15"},
        "domain": "enterprise-attack",
        "description": "Generated by secai attack_navigator_export",
        "sorting": 3, "hideDisabled": False,
        "techniques": sorted(techniques, key=lambda x: x["techniqueID"]),
        "gradient": {"colors": ["#de2d26", "#fec44f", "#2ca25f"],
                     "minValue": 0, "maxValue": 100},
    }


def analyze(techniques: list[dict], name: str) -> dict:
    layer = build_layer(techniques, name)
    covered = sum(1 for t in techniques if t["score"] >= 70)
    partial = sum(1 for t in techniques if 1 <= t["score"] < 70)
    gap = sum(1 for t in techniques if t["score"] < 1)
    f = make_finding(
        tool=TOOL, title="ATT&CK Navigator layer exported (%d techniques)" % len(techniques),
        severity="info",
        description=("Exported a Navigator layer: %d covered, %d partial, %d "
                     "gap. Upload the layer JSON to ATT&CK Navigator to view."
                     % (covered, partial, gap)),
        recommendation="Prioritize red (gap) techniques for detection coverage.",
        param="navigator:%d" % len(techniques), status="confirmed", verdict=0,
        evidence_kind="", confidence=0.9,
        extra={"kind": "navigator", "covered": covered, "partial": partial,
               "gap": gap})
    return {"schema": SCHEMA, "tool": TOOL,
            "stats": {"techniques": len(techniques), "covered": covered,
                      "partial": partial, "gap": gap, "findings": 1},
            "notes": [], "layer": layer, "findings": [f]}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Export a MITRE ATT&CK Navigator layer from coverage — offline.")
    ap.add_argument("--coverage", help="JSON attack_coverage {techniques:[...]}")
    ap.add_argument("--techniques", help="'T1059:100,T1071:50,T1566'")
    ap.add_argument("--name", default="secai coverage")
    ap.add_argument("--out-layer", help="tulis layer Navigator JSON")
    ap.add_argument("--out")
    ap.add_argument("--fail-on", default="none",
                    choices=["none", "any", "high", "medium", "low"])
    args = ap.parse_args(argv)
    try:
        if args.coverage:
            techs = _from_coverage(json.loads(Path(args.coverage).read_text(encoding="utf-8")))
        elif args.techniques:
            techs = _parse_techniques(args.techniques)
        else:
            print("[attack-navigator-export] input error: --coverage atau "
                  "--techniques wajib", file=sys.stderr)
            return 2
        result = analyze(techs, args.name)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print("[attack-navigator-export] input error: %s" % exc, file=sys.stderr)
        return 2
    result["requests"] = 0
    if args.out_layer:
        Path(args.out_layer).write_text(
            json.dumps(result["layer"], indent=2), encoding="utf-8")
    if args.out:
        write_findings(args.out, result["findings"], meta={
            "schema": SCHEMA, "tool": TOOL, "stats": result["stats"],
            "notes": [], "requests": 0})
    printable = {k: v for k, v in result.items() if k != "layer"}
    print(json.dumps(printable, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
