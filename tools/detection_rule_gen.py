"""[SAFETY: read-only, NOL jaringan] detection_rule_gen — generator aturan
Sigma + YARA dari sebuah temuan secai (findings.json). Blue-bridge: ubah
temuan jadi deteksi. TIDAK ada jaringan.

Dibangun FROM SCRATCH, stdlib murni (tanpa PyYAML — YAML Sigma minimal
dirangkai tangan). 

Ceruk vs modul lain (anti-duplikasi):
  - `yara_rule_lint.py` / `ids_rule_lint.py` = MEM-LINT aturan yang ada. Tool
    ini MENG-GENERATE Sigma + YARA baru dari temuan (keluaran lint-bersih:
    string YARA >=4 byte).

Verdict: ini bukan temuan kerentanan — tiap keluaran = L0 OBSERVED dengan teks
aturan di `poc` (opsi tulis .yml/.yar sibling). Selalu >=1 finding.

Input -> mekanisme -> output:
  - Input : --finding <findings.json kontrak> (gunakan semua temuan di dalamnya);
            --out-dir <tulis .yml/.yar per temuan, opsional>.
  - Output: JSON kontrak; --out; --fail-on. Exit 0/2.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "core"))
from findings import make_finding, write_findings  # noqa: E402

SCHEMA = "cyphron.detection-rule-gen/1"
TOOL = "detection-rule-gen"
SIGMA_LEVEL = {"critical": "critical", "high": "high", "medium": "medium",
               "low": "low", "info": "informational"}
_TOKEN = re.compile(r"[A-Za-z0-9_./:-]{4,}")   # >=4 byte utk YARA


def _keywords(f: dict, limit: int = 6) -> list[str]:
    text = " ".join(str(f.get(k, "")) for k in ("title", "param", "cwe", "evidence_kind"))
    seen: list[str] = []
    for m in _TOKEN.finditer(text):
        t = m.group(0)
        if t.lower() not in {s.lower() for s in seen}:
            seen.append(t)
        if len(seen) >= limit:
            break
    if not seen:
        seen = ["secai", "finding"]
    return seen


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9_]+", "_", (s or "rule").lower()).strip("_")[:48] or "rule"


def gen_sigma(f: dict, kws: list[str]) -> str:
    rid = hashlib.sha256((f.get("id", "") + f.get("title", "")).encode()).hexdigest()
    rid = "%s-%s-%s-%s-%s" % (rid[:8], rid[8:12], rid[12:16], rid[16:20], rid[20:32])
    lines = [
        "title: %s" % (f.get("title", "secai finding")[:80]),
        "id: %s" % rid,
        "status: experimental",
        "description: Generated by secai detection_rule_gen from a %s finding" % f.get("tool", "secai"),
        "logsource:",
        "    product: application",
        "detection:",
        "    keywords:",
    ]
    for k in kws:
        lines.append("        - '%s'" % k.replace("'", "''"))
    lines += ["    condition: keywords",
              "level: %s" % SIGMA_LEVEL.get(f.get("severity", "info"), "informational"),
              "tags:"]
    if f.get("cwe"):
        lines.append("    - %s" % f["cwe"].lower())
    return "\n".join(lines) + "\n"


def gen_yara(f: dict, kws: list[str]) -> str:
    name = "secai_%s_%s" % (_slug(f.get("tool", "secai")), (f.get("id") or "x")[:12])
    strs = []
    for i, k in enumerate(kws):
        esc = k.replace("\\", "\\\\").replace('"', '\\"')
        strs.append('        $k%d = "%s" ascii nocase' % (i, esc))
    cond = "any of them" if strs else "false"
    return ("rule %s\n{\n    meta:\n        author = \"secai\"\n"
            "        cwe = \"%s\"\n        severity = \"%s\"\n    strings:\n%s\n"
            "    condition:\n        %s\n}\n"
            % (name, f.get("cwe") or "n/a", f.get("severity", "info"),
               "\n".join(strs), cond))


def analyze(findings_in: list[dict], out_dir: str | None = None) -> dict:
    if not isinstance(findings_in, list) or not findings_in:
        raise ValueError("findings.json tidak memuat temuan")
    out: list[dict] = []
    written: list[str] = []
    for f in findings_in:
        if not isinstance(f, dict):
            continue
        kws = _keywords(f)
        sigma = gen_sigma(f, kws)
        yara = gen_yara(f, kws)
        if out_dir:
            base = _slug(f.get("tool", "secai")) + "_" + (f.get("id") or "x")[:12]
            dp = Path(out_dir)
            dp.mkdir(parents=True, exist_ok=True)
            (dp / (base + ".yml")).write_text(sigma, encoding="utf-8")
            (dp / (base + ".yar")).write_text(yara, encoding="utf-8")
            written += [str(dp / (base + ".yml")), str(dp / (base + ".yar"))]
        out.append(make_finding(
            tool=TOOL,
            title="Detection rules generated for: %s" % (f.get("title", "finding")[:70]),
            severity="info",
            description="Generated a Sigma rule and a YARA rule (strings >=4 "
                        "bytes) from the source finding.",
            recommendation="Review, tune thresholds, and deploy to your SIEM/scanner.",
            param="rulegen:%s" % (f.get("id") or f.get("title", "x"))[:60],
            status="confirmed", verdict=0, evidence_kind="",
            confidence=0.8, poc="### SIGMA\n%s\n### YARA\n%s" % (sigma, yara),
            extra={"kind": "rulegen", "keywords": kws}))
    if not out:
        raise ValueError("tidak ada temuan valid untuk digenerate")
    return {"schema": SCHEMA, "tool": TOOL,
            "stats": {"rules_for": len(out), "files_written": written,
                      "findings": len(out)},
            "notes": [], "findings": out}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate Sigma + YARA rules from a secai findings.json — offline.")
    ap.add_argument("--finding", required=True, help="findings.json kontrak")
    ap.add_argument("--out-dir", help="tulis .yml/.yar per temuan")
    ap.add_argument("--out")
    ap.add_argument("--fail-on", default="none",
                    choices=["none", "any", "high", "medium", "low"])
    args = ap.parse_args(argv)
    try:
        doc = json.loads(Path(args.finding).read_text(encoding="utf-8"))
        findings_in = doc.get("findings") if isinstance(doc, dict) else doc
        result = analyze(findings_in or [], args.out_dir)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print("[detection-rule-gen] input error: %s" % exc, file=sys.stderr)
        return 2
    result["requests"] = 0
    if args.out:
        write_findings(args.out, result["findings"], meta={
            "schema": SCHEMA, "tool": TOOL, "stats": result["stats"],
            "notes": [], "requests": 0})
    print(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
