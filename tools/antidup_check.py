"""[CONTRIB] Anti-dup pre-flight — cek duplikat SEBELUM mengerjakan target
kontribusi (template deteksi, koreksi advisory, dsb.).

Insiden yang memotivasi alat ini: PR fix untuk issue #182 disiapkan
berjam-jam, ternyata PR #183 (dari author issue itu sendiri) sudah merged
SEMBILAN MENIT sebelum PR dibuka — riset hangus. Lima cek di bawah adalah
checklist yang menyelamatkan sesi-sesi berikutnya, dikodekan supaya tidak
dilupakan:

  1. pr_refs_issue     — apakah ada PR yang mereferensikan nomor issue?
  2. recent_merged     — PR merged 14 hari terakhir yang menyentuh kata
                         kunci yang sama?
  3. keyword_search    — CVE/GHSA/kata kunci di issue+PR repo target?
  4. existing_file     — file target sudah ada di repo, atau ber-marker
                         auto-generated (updater akan menimpa PR manual)?
  5. author_intent     — body/komentar issue menunjukkan author akan
                         PR sendiri ("I'd like to add...")?

Verdict fail-closed: cek yang error dilaporkan UNKNOWN — kegagalan
jaringan tidak boleh terbaca sebagai "aman". Keluaran: ringkasan teks +
(--out) laporan JSON. Exit code: 0 = GO, 1 = STOP, 2 = CAUTION,
3 = UNKNOWN.

Pemakaian:
  export GITHUB_TOKEN=...            # opsional tapi disarankan (rate limit)
  python tools/antidup_check.py --repo projectdiscovery/nuclei-templates \
      --cve CVE-2026-102359 --keywords kroki
  python tools/antidup_check.py --repo owner/target --issue 182 \
      --file http/cves/2026/CVE-2026-XXXXX.yaml

Token dibaca dari argumen --token atau env GITHUB_TOKEN; tanpa token,
pencarian jalan unauthenticated (rate limit ~10 req/menit — cukup untuk
satu pre-flight, tidak untuk batch).
"""
from __future__ import annotations

import argparse
import base64
import datetime as dt
import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

SEARCH_URL = "https://api.github.com/search/issues"
REPO_URL = "https://api.github.com/repos"
USER_AGENT = "cyphron-antidup/1.0"
RECENT_DAYS = 14
MAX_KEYWORD_QUERIES = 3  # hemat rate limit search API

# Frasa niat author yang jelas — merampas niat orang = drama.
INTENT_PATTERNS = (
    re.compile(r"i['’]?(?:d| would) like to (?:add|submit|open|create|work)",
               re.IGNORECASE),
    re.compile(r"i(?:'m| am) (?:working|preparing|writing) on",
               re.IGNORECASE),
    re.compile(r"i(?:'ll| will) (?:submit|open|send|create) (?:a|the) PR",
               re.IGNORECASE),
    re.compile(r"\bPR (?:is|was) (?:on the way|incoming|upcoming)\b",
               re.IGNORECASE),
    re.compile(r"\bmy (?:pull request|PR)\b", re.IGNORECASE),
)

# Penanda file auto-generated (updater workflow akan menimpa PR manual).
AUTOGEN_MARKERS = ("# digest:", "<auto-generated", "@generated",
                   "do not edit", "code generated by")

VERDICT_ORDER = {"GO": 0, "CAUTION": 1, "STOP": 2, "UNKNOWN": 3}


def _get_json(url: str, token: str | None) -> dict:
    """GET satu URL GitHub API -> dict (404 = {} agar cek bisa lanjut)."""
    headers = {"User-Agent": USER_AGENT,
               "Accept": "application/vnd.github+json"}
    if token:
        headers["Authorization"] = f"token {token}"
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.load(resp)
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return {}
        raise RuntimeError(f"GitHub API HTTP {exc.code}: {url}") from exc
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise RuntimeError(f"GitHub API gagal: {url} ({exc})") from exc


def _search(query: str, token: str | None) -> list[dict]:
    """Search API issues/PR -> daftar item (hasil kosong = [])."""
    url = SEARCH_URL + "?" + urllib.parse.urlencode(
        {"q": query, "per_page": "20"})
    return _get_json(url, token).get("items", [])


class AntidupClient:
    """Pembungkus GitHub API; fetcher/search bisa disuntik untuk test."""

    def __init__(self, token: str | None = None,
                 fetch_json=None, search_fn=None):
        self.token = token
        self._fetch_json = fetch_json or (lambda url: _get_json(url, token))
        self._search = search_fn or (lambda query: _search(query, token))

    # --- cek 1: PR yang mereferensikan nomor issue ----------------------
    def check_pr_refs_issue(self, repo: str, issue_no: int) -> dict:
        items = self._search(f'"{issue_no}" type:pr repo:{repo}')
        hits = [{"number": i["number"], "title": i.get("title", ""),
                 "state": i["state"], "html_url": i["html_url"]}
                for i in items]
        return {"check": "pr_refs_issue", "verdict": "STOP" if hits else "GO",
                "hits": hits,
                "detail": (f"{len(hits)} PR menyebut issue #{issue_no}"
                           if hits else
                           f"tidak ada PR yang menyebut issue #{issue_no}")}

    # --- cek 2: PR merged 14 hari terakhir dengan kata kunci sama -------
    def check_recent_merged(self, repo: str, keywords: list[str]) -> dict:
        since = (dt.datetime.now(dt.timezone.utc)
                 - dt.timedelta(days=RECENT_DAYS)).strftime("%Y-%m-%d")
        hits: list[dict] = []
        for kw in keywords[:MAX_KEYWORD_QUERIES]:
            items = self._search(
                f'"{kw}" type:pr repo:{repo} merged:>={since}')
            hits.extend({"number": i["number"], "title": i.get("title", ""),
                         "merged_at": i.get("closed_at"),
                         "html_url": i["html_url"]}
                        for i in items)
        uniq = {h["number"]: h for h in hits}
        hits = sorted(uniq.values(), key=lambda h: h["number"])
        return {"check": "recent_merged", "verdict": "STOP" if hits else "GO",
                "hits": hits,
                "detail": (f"{len(hits)} PR merged sejak {since} menyentuh "
                           "kata kunci target" if hits else
                           f"tidak ada PR merged {RECENT_DAYS} hari "
                           "terakhir dengan kata kunci yang sama")}

    # --- cek 3: CVE/GHSA/kata kunci di issue+PR repo target -------------
    def check_keyword(self, repo: str, keywords: list[str]) -> dict:
        hits: list[dict] = []
        for kw in keywords[:MAX_KEYWORD_QUERIES]:
            items = self._search(f'"{kw}" repo:{repo}')
            hits.extend({"number": i["number"],
                         "kind": "pr" if "pull_request" in i else "issue",
                         "state": i["state"], "title": i.get("title", ""),
                         "html_url": i["html_url"]}
                        for i in items)
        uniq = {(h["number"], h["kind"]): h for h in hits}
        hits = sorted(uniq.values(), key=lambda h: h["number"])
        has_open = any(h["state"] == "open" for h in hits)
        verdict = ("STOP" if has_open
                   else "CAUTION" if hits else "GO")
        return {"check": "keyword_search", "verdict": verdict, "hits": hits,
                "detail": (f"{len(hits)} item menyebut target "
                           f"({'ada yang open' if has_open else
                               'semua closed'})")}

    # --- cek 4: file sudah ada / auto-generated -------------------------
    def check_existing_file(self, repo: str, branch: str,
                            file_path: str) -> dict:
        url = (f"{REPO_URL}/{repo}/contents/"
               + urllib.parse.quote(file_path) + f"?ref={branch}")
        data = self._fetch_json(url)
        if not data or "content" not in data:
            return {"check": "existing_file", "verdict": "GO", "hits": [],
                    "detail": f"file {file_path} belum ada di "
                              f"{repo}@{branch} — aman untuk tambahan baru"}
        content = base64.b64decode(data.get("content", "")).decode(
            "utf-8", errors="replace")
        markers = [m for m in AUTOGEN_MARKERS if m.lower() in content.lower()]
        if markers:
            return {"check": "existing_file", "verdict": "STOP",
                    "hits": markers,
                    "detail": (f"file {file_path} ADA dan ber-marker "
                               "auto-generated — PR manual bakal ditimpa "
                               "updater")}
        return {"check": "existing_file", "verdict": "STOP",
                "hits": [file_path],
                "detail": (f"file {file_path} SUDAH ada di {repo}@{branch} "
                           "— ini pekerjaan ubah, bukan tambah")}

    # --- cek 5: niat author di body/komentar issue ----------------------
    def check_author_intent(self, repo: str, issue_no: int) -> dict:
        issue = self._fetch_json(f"{REPO_URL}/{repo}/issues/{issue_no}")
        comments = self._fetch_json(
            f"{REPO_URL}/{repo}/issues/{issue_no}/comments")
        if not issue and not comments:
            return {"check": "author_intent", "verdict": "UNKNOWN",
                    "hits": [],
                    "detail": f"issue #{issue_no} tidak dapat dibaca "
                              "(repo salah atau issue tidak ada)"}
        texts = [issue.get("body") or ""] + [
            c.get("body") or "" for c in comments]
        hits: list[str] = []
        for text in texts:
            for pat in INTENT_PATTERNS:
                found = pat.search(text)
                if found:
                    hits.append(found.group(0)[:80])
        verdict = "STOP" if hits else "GO"
        return {"check": "author_intent", "verdict": verdict,
                "hits": sorted(set(hits)),
                "detail": ("sinyal niat author ditemukan — jangan rampas "
                           "niat" if hits else
                           f"tidak ada sinyal niat author di issue "
                           f"#{issue_no}")}


def merge_verdict(checks: list[dict]) -> tuple[str, list[dict]]:
    """Gabungkan verdict per-cek -> final; PASS dinormalisasi jadi GO dan
    verdict tak dikenal dianggap UNKNOWN (fail-closed)."""
    final = "GO"
    reasons: list[dict] = []
    for check in checks:
        verdict = check.get("verdict")
        if verdict == "PASS":
            verdict = "GO"
        if verdict not in VERDICT_ORDER:
            verdict = "UNKNOWN"
        if VERDICT_ORDER[verdict] > VERDICT_ORDER[final]:
            final = verdict
        if verdict in ("STOP", "CAUTION", "UNKNOWN"):
            reasons.append({"check": check.get("check"), "verdict": verdict,
                            "detail": check.get("detail", ""),
                            "hits": check.get("hits", [])})
    return final, reasons


def run(repo: str, keywords: list[str], issue_no: int | None,
        file_path: str | None, branch: str, token: str | None,
        client: "AntidupClient | None" = None) -> dict:
    """Jalankan semua cek yang relevan; cek error = UNKNOWN, bukan PASS.

    `client` bisa disuntik untuk test offline (Nol jaringan).
    """
    client = client or AntidupClient(token=token)
    checks: list[dict] = []
    errors: list[str] = []

    def guarded(label: str, fn) -> None:
        try:
            checks.append(fn())
        except RuntimeError as exc:
            errors.append(f"{label}: {exc}")
            checks.append({"check": label, "verdict": "UNKNOWN",
                           "detail": str(exc), "hits": []})

    if issue_no:
        guarded("pr_refs_issue",
                lambda: client.check_pr_refs_issue(repo, issue_no))
    if keywords:
        guarded("recent_merged",
                lambda: client.check_recent_merged(repo, keywords))
        guarded("keyword_search",
                lambda: client.check_keyword(repo, keywords))
    if file_path:
        guarded("existing_file",
                lambda: client.check_existing_file(repo, branch, file_path))
    if issue_no:
        guarded("author_intent",
                lambda: client.check_author_intent(repo, issue_no))

    final, reasons = merge_verdict(checks)
    if not checks:
        final = "UNKNOWN"
        reasons.append({"check": "none", "verdict": "UNKNOWN",
                        "detail": "tidak ada cek yang dijalankan — berikan "
                                  "minimal --cve/--ghsa/--keywords, "
                                  "--issue, atau --file",
                        "hits": []})
    return {"repo": repo, "final_verdict": final, "checks": checks,
            "reasons": reasons, "api_errors": errors}


def resolve_branch(client: AntidupClient, repo: str) -> str:
    """Default branch repo target; gagal = 'main' + peringatan."""
    try:
        data = client._fetch_json(f"{REPO_URL}/{repo}")
        if data.get("default_branch"):
            return data["default_branch"]
    except RuntimeError as exc:
        print(f"WARN: gagal resolve default branch ({exc}); pakai main",
              file=sys.stderr)
    return "main"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Anti-dup pre-flight untuk target kontribusi "
                    "(5 cek protokol anti-dup v2).")
    parser.add_argument("--repo", required=True,
                        help="repo target, mis. projectdiscovery/nuclei-templates")
    parser.add_argument("--cve", default=None, help="ID CVE target")
    parser.add_argument("--ghsa", default=None, help="ID GHSA target")
    parser.add_argument("--issue", type=int, default=None,
                        help="nomor issue target (aktifkan cek 1 & 5)")
    parser.add_argument("--file", default=None,
                        help="path file target di repo (cek 4)")
    parser.add_argument("--branch", default=None,
                        help="branch acuan cek 4 (default: default branch)")
    parser.add_argument("--keywords", default=None,
                        help="kata kunci tambahan, koma-pisah")
    parser.add_argument("--token", default=None,
                        help="token GitHub (default: env GITHUB_TOKEN)")
    parser.add_argument("--out", default=None,
                        help="tulis laporan JSON ke file ini")
    args = parser.parse_args(argv)

    token = args.token or os.environ.get("GITHUB_TOKEN") or None
    client = AntidupClient(token=token)
    branch = args.branch or resolve_branch(client, args.repo)

    keywords = [k for k in (args.cve, args.ghsa) if k]
    if args.keywords:
        keywords += [k.strip() for k in args.keywords.split(",")
                     if k.strip()]

    report = run(args.repo, keywords, args.issue, args.file, branch, token)

    if args.out:
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(
            json.dumps(report, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8")

    print(f"repo    : {report['repo']}")
    for check in report["checks"]:
        print(f"  [{check['verdict']:<7}] {check['check']:<16} "
              f"{check['detail']}")
    for err in report["api_errors"]:
        print(f"  [ERR    ] {err}")
    print(f"verdict : {report['final_verdict']}")
    if args.out:
        print(f"laporan : {args.out}")

    return {"GO": 0, "STOP": 1, "CAUTION": 2,
            "UNKNOWN": 3}[report["final_verdict"]]


if __name__ == "__main__":
    sys.exit(main())
